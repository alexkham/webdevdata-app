// generate-reference-catalogs.mjs
//
// Auto-generates the /reference catalogs and the emulator map from the
// per-item content files under content/reference/.
//
// The script contains NO content. Everything comes from the `meta` named
// export of each content file:
//
//   content/reference/<language>/<category>/<slug>.js
//     export const meta = { slug, name, signature, blurb, category, type,
//                           hasLiveDemo, version, searchTerms };
//
// Method: AST-parse each file with @babel/parser and literal-evaluate ONLY
// the `meta` export. No require, no eval — the heavy `method` export is
// never touched here.
//
// Cross-check: every meta with hasLiveDemo:true must have a matching
// emulator at utils/emulators/<language>/<slug>.js — warns if missing.
//
// Output (all files start with AUTO-GENERATED headers):
//   data/generated/reference-catalog.js         all languages, all categories
//   data/generated/python-functions-catalog.js  flat list for the explorer
//   data/generated/python-rollup.js             counts by type, featured picks
//   utils/emulators-map.js                      slug → emulator function
//
// Wire into package.json:
//   "dev":   "... && node generate-reference-catalogs.mjs && next dev"
//   "build": "... && node generate-reference-catalogs.mjs && next build ..."

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { parse } from '@babel/parser';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const CONTENT_DIR = path.join(__dirname, 'content', 'reference');
const EMULATORS_DIR = path.join(__dirname, 'utils', 'emulators');
const GENERATED_DIR = path.join(__dirname, 'data', 'generated');
const EMULATORS_MAP_FILE = path.join(__dirname, 'utils', 'emulators-map.js');

const AUTO_HEADER = (script) => `// AUTO-GENERATED by ${script}
// Regenerated on every \`npm run dev\` and \`npm run build\`.
// Do NOT edit by hand — changes here are overwritten.
`;

// ─────────────────────────────────────────────────────────────
// Literal evaluation of the `meta` ObjectExpression
// ─────────────────────────────────────────────────────────────

function evalLiteral(node, warnings, file) {
  switch (node.type) {
    case 'StringLiteral':
    case 'NumericLiteral':
    case 'BooleanLiteral':
      return node.value;
    case 'NullLiteral':
      return null;
    case 'UnaryExpression':
      if (node.operator === '-') return -evalLiteral(node.argument, warnings, file);
      break;
    case 'TemplateLiteral':
      if (node.expressions.length === 0) return node.quasis.map((q) => q.value.cooked).join('');
      break;
    case 'ArrayExpression':
      return node.elements.map((el) => evalLiteral(el, warnings, file));
    case 'ObjectExpression': {
      const obj = {};
      for (const prop of node.properties) {
        if (prop.type !== 'ObjectProperty' || prop.computed) {
          warnings.push(`[warn] non-literal property in meta of ${file} — skipped`);
          continue;
        }
        const key = prop.key.type === 'Identifier' ? prop.key.name : prop.key.value;
        obj[key] = evalLiteral(prop.value, warnings, file);
      }
      return obj;
    }
    default:
      break;
  }
  warnings.push(`[warn] non-literal value (${node.type}) in meta of ${file}`);
  return null;
}

// Extract the `export const meta = {...}` object from a content file, or null.
function extractMeta(src, file, warnings) {
  let ast;
  try {
    ast = parse(src, { sourceType: 'module' });
  } catch (e) {
    warnings.push(`[warn] parse error in ${file}: ${e.message} — file skipped`);
    return null;
  }

  for (const stmt of ast.program.body) {
    if (stmt.type !== 'ExportNamedDeclaration' || !stmt.declaration) continue;
    if (stmt.declaration.type !== 'VariableDeclaration') continue;
    for (const decl of stmt.declaration.declarations) {
      if (decl.id.type === 'Identifier' && decl.id.name === 'meta') {
        if (!decl.init || decl.init.type !== 'ObjectExpression') {
          warnings.push(`[warn] meta export is not an object literal in ${file} — file skipped`);
          return null;
        }
        return evalLiteral(decl.init, warnings, file);
      }
    }
  }
  warnings.push(`[warn] no meta export found in ${file} — file skipped`);
  return null;
}

// ─────────────────────────────────────────────────────────────
// Walk content/reference/<language>/<category>/<slug>.js
// ─────────────────────────────────────────────────────────────

function collectContent(warnings) {
  const items = []; // { language, category (folder), slug (filename), meta }
  if (!fs.existsSync(CONTENT_DIR)) {
    warnings.push(`[warn] content dir not found: ${CONTENT_DIR}`);
    return items;
  }
  for (const lang of fs.readdirSync(CONTENT_DIR, { withFileTypes: true })) {
    if (!lang.isDirectory()) continue;
    const langDir = path.join(CONTENT_DIR, lang.name);
    for (const cat of fs.readdirSync(langDir, { withFileTypes: true })) {
      if (!cat.isDirectory()) continue;
      const catDir = path.join(langDir, cat.name);
      for (const f of fs.readdirSync(catDir)) {
        if (!f.endsWith('.js')) continue;
        const filePath = path.join(catDir, f);
        const rel = `content/reference/${lang.name}/${cat.name}/${f}`;
        const src = fs.readFileSync(filePath, 'utf8');
        const meta = extractMeta(src, rel, warnings);
        if (!meta) continue;

        const fileSlug = f.replace(/\.js$/, '');
        if (meta.slug && meta.slug !== fileSlug) {
          warnings.push(`[warn] meta.slug "${meta.slug}" != filename "${fileSlug}" in ${rel} — using filename`);
        }
        items.push({
          language: lang.name,
          category: cat.name,
          slug: fileSlug,
          meta: { ...meta, slug: fileSlug },
        });
      }
    }
  }
  return items;
}

// ─────────────────────────────────────────────────────────────
// Emulator cross-check
// ─────────────────────────────────────────────────────────────

function checkEmulators(items, warnings) {
  const withEmulator = []; // { language, slug, file }
  const seenSlugs = new Map();

  for (const item of items) {
    if (!item.meta.hasLiveDemo) continue;
    const emuFile = path.join(EMULATORS_DIR, item.language, `${item.slug}.js`);
    if (!fs.existsSync(emuFile)) {
      warnings.push(`[warn] hasLiveDemo:true but no emulator at utils/emulators/${item.language}/${item.slug}.js (${item.language}/${item.category}/${item.slug})`);
      continue;
    }
    if (seenSlugs.has(item.slug)) {
      warnings.push(`[warn] emulator slug collision: "${item.slug}" in ${item.language} and ${seenSlugs.get(item.slug)} — map keeps the first`);
      continue;
    }
    seenSlugs.set(item.slug, item.language);
    withEmulator.push({ language: item.language, slug: item.slug });
  }
  return withEmulator;
}

// ─────────────────────────────────────────────────────────────
// Emitters
// ─────────────────────────────────────────────────────────────

function emitReferenceCatalog(items) {
  const byLang = new Map();
  for (const it of items) {
    if (!byLang.has(it.language)) byLang.set(it.language, new Map());
    const byCat = byLang.get(it.language);
    if (!byCat.has(it.category)) byCat.set(it.category, []);
    byCat.get(it.category).push(it.meta);
  }

  const languages = [...byLang.entries()].map(([lang, byCat]) => {
    const categories = [...byCat.entries()].map(([cat, metas]) => ({
      id: cat,
      href: `/reference/${lang}/${cat}`,
      count: metas.length,
      liveCount: metas.filter((m) => m.hasLiveDemo).length,
      items: metas,
    }));
    const count = categories.reduce((n, c) => n + c.count, 0);
    return { id: lang, href: `/reference/${lang}`, count, categories };
  });

  const out = `${AUTO_HEADER('generate-reference-catalogs.mjs')}//
// All languages, all categories. Source of truth: the meta export of every
// file under content/reference/.

export const referenceCatalog = {
  generatedAt: ${JSON.stringify(new Date().toISOString())},
  languages: ${JSON.stringify(languages, null, 2)}
};
`;
  fs.writeFileSync(path.join(GENERATED_DIR, 'reference-catalog.js'), out);
  return languages;
}

function emitPythonFunctionsCatalog(items) {
  const metas = items
    .filter((it) => it.language === 'python' && it.category === 'functions')
    .map((it) => it.meta);

  const out = `${AUTO_HEADER('generate-reference-catalogs.mjs')}//
// Flat list for the /reference/python/functions explorer.

export const pythonFunctionsCatalog = {
  generatedAt: ${JSON.stringify(new Date().toISOString())},
  items: ${JSON.stringify(metas, null, 2)}
};
`;
  fs.writeFileSync(path.join(GENERATED_DIR, 'python-functions-catalog.js'), out);
  return metas;
}

function emitPythonRollup(metas) {
  const byType = new Map();
  for (const m of metas) {
    const t = m.type || 'other';
    byType.set(t, (byType.get(t) || 0) + 1);
  }
  const types = [...byType.entries()].map(([type, count]) => ({ type, count }));

  const byCategory = new Map();
  for (const m of metas) {
    const c = m.category || 'other';
    byCategory.set(c, (byCategory.get(c) || 0) + 1);
  }
  const categories = [...byCategory.entries()].map(([category, count]) => ({ category, count }));

  const featured = metas.filter((m) => m.hasLiveDemo).slice(0, 6);

  const out = `${AUTO_HEADER('generate-reference-catalogs.mjs')}//
// Rollup for the /reference/python landing: counts by type/category,
// featured picks (live-demo items, discovery order).

export const pythonRollup = {
  generatedAt: ${JSON.stringify(new Date().toISOString())},
  total: ${metas.length},
  liveTotal: ${metas.filter((m) => m.hasLiveDemo).length},
  types: ${JSON.stringify(types, null, 2)},
  categories: ${JSON.stringify(categories, null, 2)},
  featured: ${JSON.stringify(featured, null, 2)}
};
`;
  fs.writeFileSync(path.join(GENERATED_DIR, 'python-rollup.js'), out);
}

function emitEmulatorsMap(withEmulator) {
  const ident = (slug) => slug.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()) + 'Emu';

  const imports = withEmulator
    .map(({ language, slug }) => `import ${ident(slug)} from './emulators/${language}/${slug}';`)
    .join('\n');
  const entries = withEmulator
    .map(({ slug }) => `  '${slug}': ${ident(slug)},`)
    .join('\n');

  const out = `${AUTO_HEADER('generate-reference-catalogs.mjs')}//
// slug → emulator function, for every content item with hasLiveDemo:true
// whose emulator file exists. Static imports — predictable bundling.

${imports}

const emulators = {
${entries}
};

export function getEmulator(slug) {
  return emulators[slug];
}
`;
  fs.writeFileSync(EMULATORS_MAP_FILE, out);
}

// ─────────────────────────────────────────────────────────────
// Main
// ─────────────────────────────────────────────────────────────

function main() {
  const warnings = [];

  const items = collectContent(warnings);
  const withEmulator = checkEmulators(items, warnings);

  fs.mkdirSync(GENERATED_DIR, { recursive: true });
  const languages = emitReferenceCatalog(items);
  const pyFunctions = emitPythonFunctionsCatalog(items);
  emitPythonRollup(pyFunctions);
  emitEmulatorsMap(withEmulator);

  warnings.forEach((w) => console.warn(`  ${w}`));
  console.log(`\nReference catalogs generated: ${items.length} item(s), ${withEmulator.length} emulator(s) mapped`);
  languages.forEach((l) => {
    console.log(`  [${l.id}] ${l.count} item(s) in ${l.categories.length} categorie(s)`);
  });
  console.log(`\nWritten to: ${GENERATED_DIR} and ${EMULATORS_MAP_FILE}\n`);
}

main();
